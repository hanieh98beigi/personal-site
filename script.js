function storageGet(key, fallback) {
  try { return localStorage.getItem(key) || fallback; } catch { return fallback; }
}
function storageSet(key, value) {
  try { localStorage.setItem(key, value); } catch { /* ignore storage restrictions */ }
}
function setLang(lang) {
  const dict = T[lang] || T.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl', lang === 'fa');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(dict, key)) el.innerHTML = dict[key];
  });
  const langButton = document.getElementById('language');
  if (langButton) langButton.textContent = lang === 'fa' ? 'EN' : 'FA';
  document.title = lang === 'fa' ? 'هانیه اسدبیگی — مدیر محصول داده‌محور' : 'Haniyeh Asadbeigi — Data-Informed Product Manager';
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = lang === 'fa'
    ? 'هانیه اسدبیگی، مدیر محصول با تمرکز بر نیاز مشتری، تصمیم‌گیری داده‌محور و تجربه اسکرام‌مستری.'
    : 'Haniyeh Asadbeigi — Associate Product Manager with Scrum Master experience, focused on customer needs, data-informed decisions, and product delivery.';
  storageSet('site-lang', lang);
}
function setTheme(theme) {
  const dark = theme === 'dark';
  document.body.classList.toggle('dark', dark);
  const button = document.getElementById('theme');
  if (button) button.textContent = dark ? '☼' : '☾';
  storageSet('site-theme', dark ? 'dark' : 'light');
}

document.addEventListener('DOMContentLoaded', () => {
  const language = document.getElementById('language');
  const theme = document.getElementById('theme');
  language?.addEventListener('click', () => setLang(document.documentElement.lang === 'en' ? 'fa' : 'en'));
  theme?.addEventListener('click', () => setTheme(document.body.classList.contains('dark') ? 'light' : 'dark'));

  setLang(storageGet('site-lang', 'en'));
  setTheme(storageGet('site-theme', 'light'));

  const year = document.getElementById('year');
  if (year) year.textContent = new Date().getFullYear();

  const revealEls = document.querySelectorAll('.reveal');
  if ('IntersectionObserver' in window) {
    const io = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('in');
          io.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12 });
    revealEls.forEach(el => io.observe(el));
  } else {
    revealEls.forEach(el => el.classList.add('in'));
  }
});
